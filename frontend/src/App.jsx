import { useEffect, useState } from 'react';
import {
  Area,
  AreaChart,
  Bar,
  BarChart,
  CartesianGrid,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import StatCard from './components/StatCard';
import { analyzeSatelliteImage, fetchDashboard } from './services/api';

const navigation = [
  ['dashboard', 'Dashboard'],
  ['analysis', 'Cyclone Analysis'],
  ['analysis', 'Satellite Upload'],
  ['track', 'Track Prediction'],
  ['classification', 'Intensity Classification'],
  ['history', 'Historical Cyclones'],
  ['performance', 'Model Performance'],
  ['alerts', 'Alerts'],
];

function formatConfidence(value) {
  return typeof value === 'number' ? `${Math.round(value * 100)}%` : 'Not available';
}

function formatCoordinate(value, positiveDirection, negativeDirection) {
  if (typeof value !== 'number') return 'Not provided';
  return `${Math.abs(value).toFixed(1)}°${value < 0 ? negativeDirection : positiveDirection}`;
}

function ProbabilityDistribution({ probabilities, source, title = 'IMD INTENSITY PROBABILITY', note }) {
  if (!probabilities?.length) {
    return <p className="empty-state">Eight-class probability output was not returned by the API.</p>;
  }

  return (
    <section className="panel">
      <div className="panel-header">
        <h3>{title}</h3>
        <span className={`source-badge ${source === 'model' ? 'source-model' : ''}`}>
          {source === 'model' ? 'MODEL OUTPUT' : 'DEMO DATA'}
        </span>
      </div>
      {(note || source !== 'model') && (
        <p className="demo-note">{note || 'Illustrative probabilities only; not generated by the current prototype classifier.'}</p>
      )}
      <div className="probability-chart">
        <ResponsiveContainer width="100%" height={280}>
          <BarChart data={probabilities} layout="vertical" margin={{ top: 4, right: 22, left: 12, bottom: 4 }}>
            <CartesianGrid stroke="rgba(255,255,255,0.08)" horizontal={false} />
            <XAxis
              type="number"
              domain={[0, 100]}
              unit="%"
              stroke="#a7b4c7"
              tick={{ fontSize: 12 }}
            />
            <YAxis
              type="category"
              dataKey="class_name"
              width={190}
              stroke="#a7b4c7"
              tick={{ fontSize: 12 }}
            />
            <Tooltip formatter={(value) => [`${value}%`, 'Probability']} />
            <Bar dataKey="probability" fill="#4ea1ff" radius={[0, 6, 6, 0]} />
          </BarChart>
        </ResponsiveContainer>
      </div>
    </section>
  );
}

function CoordinateList({ title, points, kind }) {
  return (
    <section className="panel">
      <div className="panel-header">
        <h3>{title}</h3>
        <span className="source-badge">DEMO DATA</span>
      </div>
      {points?.length ? (
        <div className="track-list">
          {points.map((point, index) => (
            <div className="track-row track-row-timestamp" key={`${point.timestamp || point.hours}-${index}`}>
              <span>{point.time_label || `+${point.hours}h`}</span>
              <strong>
                {formatCoordinate(point.latitude, 'N', 'S')},{' '}
                {formatCoordinate(point.longitude, 'E', 'W')}
              </strong>
            </div>
          ))}
        </div>
      ) : (
        <p className="empty-state">No {kind.toLowerCase()} coordinates are available.</p>
      )}
    </section>
  );
}

function App() {
  const [activePage, setActivePage] = useState('dashboard');
  const [dashboard, setDashboard] = useState(null);
  const [dashboardError, setDashboardError] = useState('');
  const [isLoading, setIsLoading] = useState(true);
  const [selectedFile, setSelectedFile] = useState(null);
  const [previewUrl, setPreviewUrl] = useState('');
  const [analysisResult, setAnalysisResult] = useState(null);
  const [analysisError, setAnalysisError] = useState('');
  const [isAnalyzing, setIsAnalyzing] = useState(false);
  const [analysisHistory, setAnalysisHistory] = useState([]);

  async function loadDashboard() {
    setIsLoading(true);
    setDashboardError('');
    try {
      setDashboard(await fetchDashboard());
    } catch (error) {
      setDashboardError(error.message || 'Could not load dashboard data.');
    } finally {
      setIsLoading(false);
    }
  }

  useEffect(() => {
    loadDashboard();
  }, []);

  useEffect(() => {
    if (!selectedFile) {
      setPreviewUrl('');
      return undefined;
    }
    const objectUrl = URL.createObjectURL(selectedFile);
    setPreviewUrl(objectUrl);
    return () => URL.revokeObjectURL(objectUrl);
  }, [selectedFile]);

  async function submitAnalysis(event) {
    event.preventDefault();
    if (!selectedFile) {
      setAnalysisError('Choose a satellite image before starting analysis.');
      return;
    }
    setIsAnalyzing(true);
    setAnalysisError('');
    setAnalysisResult(null);
    try {
      const result = await analyzeSatelliteImage(selectedFile);
      setAnalysisResult(result);
      setAnalysisHistory((items) => [
        {
          filename: selectedFile.name,
          cyclone_detected: result.cyclone_detected,
          classification: result.classification,
          classification_confidence: result.classification_confidence,
          analysis_timestamp: result.analysis_timestamp,
          data_mode: result.data_mode,
        },
        ...items,
      ].slice(0, 20));
    } catch (error) {
      setAnalysisError(error.message || 'Image analysis failed.');
    } finally {
      setIsAnalyzing(false);
    }
  }

  if (isLoading) {
    return <div className="app-message">Loading Cyclo Sense dashboard…</div>;
  }

  if (!dashboard) {
    return (
      <div className="app-message">
        <h1>Dashboard unavailable</h1>
        <p>{dashboardError || 'The API did not return dashboard data.'}</p>
        <button className="primary-button" onClick={loadDashboard}>Retry connection</button>
      </div>
    );
  }

  const selectedCyclone = dashboard.selected_cyclone;
  const isDemo = dashboard.model_status?.demo_mode || dashboard.probabilities_source === 'demo';

  function renderDashboard() {
    return (
      <>
        <section className="hero-card">
          <div className="hero-copy">
            <div className="label-pill">Current analysis · {selectedCyclone.cyclone_id}</div>
            <h2>{selectedCyclone.cyclone_name}</h2>
            <div className="hero-grid">
              <div><span>Cyclone detection</span><strong>{selectedCyclone.detection ? 'YES' : 'NO'}</strong></div>
              <div className="classification-result">
                <span>IMD intensity classification</span>
                <strong>{selectedCyclone.imd_classification}</strong>
              </div>
              <div><span>Confidence</span><strong>{formatConfidence(selectedCyclone.classification_confidence)}</strong></div>
            </div>
          </div>
          <div className="hero-side">
            <div className="mini-panel"><span>Current wind speed · supporting information</span><strong>{selectedCyclone.wind_speed_kmh} km/h</strong></div>
            <div className="mini-panel"><span>Evolution · demo observations</span><strong className="evolution-value">↗ {dashboard.evolution_status}</strong></div>
            <button className="primary-button" onClick={() => setActivePage('track')}>View cyclone track</button>
          </div>
        </section>

        <section className="stats-grid">
          <StatCard label="Active cyclone count" value={dashboard.summary.active_cyclone_count} detail="demo dataset" accent="blue" />
          <StatCard label="Latest analysis" value={dashboard.summary.latest_analysis_time} detail="demo timestamp" accent="green" />
          <StatCard label="Detection" value={selectedCyclone.detection ? 'YES' : 'NO'} detail={`confidence ${formatConfidence(selectedCyclone.detection_confidence)}`} accent="amber" />
          <StatCard label="System status" value={dashboard.health.status === 'ok' ? 'Healthy' : 'Unavailable'} detail={isDemo ? 'DEMO MODE' : dashboard.health.environment} accent="red" />
        </section>

        {isDemo && <p className="demo-banner">DEMO MODE — synthetic sample data; not live meteorological observations or official warnings.</p>}

        <section className="panel">
          <div className="panel-header"><h3>Model capability status</h3><span className="source-badge">CHECKPOINT-BASED</span></div>
          <div className="result-list">
            <div><span>Cyclone detection prototype</span><strong>{dashboard.model_status?.detection_model_ready ? 'Checkpoint available' : 'Unavailable'}</strong></div>
            <div><span>Four-stage prototype classification</span><strong>{dashboard.model_status?.classification_model_ready ? 'Synthetic-trained only' : 'Unavailable'}</strong></div>
            <div><span>Grad-CAM</span><strong>{dashboard.model_status?.gradcam_ready ? 'Prototype explanation available' : 'Unavailable'}</strong></div>
            <div><span>Eight-class IMD, intensity forecast, track forecast, risk</span><strong>Unavailable — no trained artifacts</strong></div>
          </div>
          {dashboard.model_status?.model_provenance && <p className="demo-note">{dashboard.model_status.model_provenance}</p>}
        </section>

        <section className="content-grid">
          <ProbabilityDistribution
            probabilities={dashboard.imd_intensity_probabilities}
            source={dashboard.probabilities_source}
          />
          <section className="panel">
            <div className="panel-header">
              <h3>Timestamped intensity analysis</h3>
              <span className="source-badge">DEMO DATA</span>
            </div>
            <div className="timeline-list">
              {dashboard.timestamped_observations.map((observation) => (
                <div className="timeline-row" key={observation.timestamp}>
                  <time>{observation.time_label}</time>
                  <strong>{observation.classification}</strong>
                </div>
              ))}
            </div>
            <div className="evolution-summary">
              <span>Intensity evolution</span>
              <strong>↗ {dashboard.evolution_status}</strong>
              <small>Derived from ordered timestamped demo observations.</small>
            </div>
          </section>
        </section>

        <section className="content-grid">
          <CoordinateList title="Observed track" points={dashboard.observed_track} kind="observed" />
          <CoordinateList title="Predicted track" points={dashboard.predicted_track} kind="predicted" />
        </section>

        <section className="content-grid">
          <section className="panel">
            <div className="panel-header">
              <h3>Future intensity forecast</h3>
              <span className="source-badge">DEMO FORECAST · NOT A CLASSIFICATION</span>
            </div>
            <div className="chart-box">
              <ResponsiveContainer width="100%" height={220}>
                <AreaChart data={dashboard.intensity_forecast}>
                  <defs>
                    <linearGradient id="areaFill" x1="0" x2="0" y1="0" y2="1">
                      <stop offset="5%" stopColor="#4ecdc4" stopOpacity={0.8} />
                      <stop offset="95%" stopColor="#4ecdc4" stopOpacity={0.08} />
                    </linearGradient>
                  </defs>
                  <CartesianGrid stroke="rgba(255,255,255,0.08)" vertical={false} />
                  <XAxis dataKey="name" stroke="#a7b4c7" />
                  <YAxis stroke="#a7b4c7" unit=" km/h" />
                  <Tooltip formatter={(value) => [`${value} km/h`, 'Forecast wind speed']} />
                  <Area type="monotone" dataKey="value" stroke="#4ecdc4" fill="url(#areaFill)" strokeWidth={2} />
                </AreaChart>
              </ResponsiveContainer>
            </div>
          </section>
          <PredictionTable predictions={dashboard.predictions} />
        </section>

        <ModelInformation information={dashboard.model_information} />
      </>
    );
  }

  function renderAnalysis() {
    const result = analysisResult;
    const resultHasImdProbabilities = Boolean(result?.imd_probabilities);

    return (
      <section className="page-content">
        <div className="page-title">
          <p className="eyebrow">Satellite data · prototype inference</p>
          <h2>Satellite Analysis</h2>
          <p>Upload an image for available prototype detection and four-stage classification. The current model does not return an eight-class IMD result.</p>
        </div>
        <div className="content-grid">
          <form className="panel upload-panel" onSubmit={submitAnalysis}>
            <h3>Upload satellite image</h3>
            <label className="file-input-label">
              Select PNG or JPEG
              <input
                type="file"
                accept="image/png,image/jpeg"
                onChange={(event) => {
                  setSelectedFile(event.target.files?.[0] || null);
                  setAnalysisResult(null);
                  setAnalysisError('');
                }}
              />
            </label>
            {previewUrl && (
              <div className="uploaded-image">
                <h4>Uploaded satellite image</h4>
                <img className="image-preview" src={previewUrl} alt="Uploaded satellite image preview" />
              </div>
            )}
            {selectedFile && <p className="muted-copy">{selectedFile.name}</p>}
            <button className="primary-button" type="submit" disabled={isAnalyzing}>
              {isAnalyzing ? 'Analyzing…' : 'Analyze image'}
            </button>
            {analysisError && <p className="error-message" role="alert">{analysisError}</p>}
          </form>

          <section className="panel">
            <div className="panel-header">
              <h3>Analysis result</h3>
              <span className="source-badge">{result ? 'PROTOTYPE MODEL' : 'AWAITING IMAGE'}</span>
            </div>
            {result ? (
              <div className="result-list">
                <div><span>Cyclone detection</span><strong>{result.cyclone_detected ? 'YES' : 'NO'}</strong></div>
                <div><span>Detection confidence</span><strong>{formatConfidence(result.detection_confidence)}</strong></div>
                <div><span>IMD intensity classification</span><strong>{result.imd_classification || 'Not available from current model'}</strong></div>
                <div><span>Prototype stage classification</span><strong>{result.classification || 'Not returned'}</strong></div>
                <div><span>Stage confidence</span><strong>{formatConfidence(result.classification_confidence)}</strong></div>
                <div><span>Analysis timestamp (UTC)</span><strong>{new Date(result.analysis_timestamp).toLocaleString('en-GB', { timeZone: 'UTC', hour12: false })} UTC</strong></div>
                <div><span>Latitude / longitude</span><strong>{formatCoordinate(result.latitude, 'N', 'S')}, {formatCoordinate(result.longitude, 'E', 'W')}</strong></div>
                <div><span>Wind speed</span><strong>{result.wind_speed_kmh == null ? 'Not provided by API' : `${result.wind_speed_kmh} km/h`}</strong></div>
                <div><span>Evolution</span><strong>{result.evolution_status || 'Insufficient temporal data'}</strong></div>
              </div>
            ) : (
              <p className="empty-state">Choose an image to run the available prototype analysis.</p>
            )}
            {result?.model_provenance && <p className="demo-note">{result.model_provenance}</p>}
            <p className="demo-note">IMD intensity, wind speed, coordinates, evolution, and risk are shown only when supported by a model or supplied observation data.</p>
          </section>
        </div>
        {resultHasImdProbabilities ? (
          <ProbabilityDistribution
            probabilities={Object.entries(result.imd_probabilities).map(([class_name, probability]) => ({
              class_name,
              probability: probability <= 1 ? probability * 100 : probability,
            }))}
            source="model"
            title="IMD probabilities returned by model"
          />
        ) : result ? (
          <section className="panel">
            <h3>IMD intensity result unavailable</h3>
            <p>The available classifier only predicts four synthetic development stages; it does not produce an IMD class.</p>
          </section>
        ) : (
          <ProbabilityDistribution
            probabilities={dashboard.imd_intensity_probabilities}
            source={dashboard.probabilities_source}
            title="IMD probability reference · dashboard demo"
            note="These illustrative values are demo data and are not predictions for an uploaded image."
          />
        )}
        {result?.stage_probabilities && (
          <section className="panel">
            <div className="panel-header"><h3>Four synthetic prototype stages</h3><span className="source-badge source-model">{result.data_mode || 'PROTOTYPE OUTPUT'}</span></div>
            <div className="stage-probabilities">
              {Object.entries(result.stage_probabilities).map(([name, probability]) => (
                <div key={name}><span>{name}</span><strong>{formatConfidence(probability)}</strong></div>
              ))}
            </div>
          </section>
        )}
        {result?.explanation_image && (
          <section className="panel">
            <div className="panel-header"><h3>Grad-CAM explanation</h3><span className="source-badge source-model">PROTOTYPE ONLY</span></div>
            <p className="demo-note">Highlighted regions show where the synthetic-trained classifier focused; this is not a validated meteorological explanation.</p>
            <img className="image-preview" src={result.explanation_image} alt="Grad-CAM heatmap for the prototype stage prediction" />
          </section>
        )}
      </section>
    );
  }

  function renderTrack() {
    return (
      <section className="page-content">
        <div className="page-title"><p className="eyebrow">Location history and forecast</p><h2>Cyclone Track</h2></div>
        <p className="demo-banner">Observed and predicted points are shown separately. The current dashboard sample is DEMO DATA.</p>
        <section className="content-grid">
          <CoordinateList title="Observed track" points={dashboard.observed_track} kind="observed" />
          <CoordinateList title="Predicted track" points={dashboard.predicted_track} kind="predicted" />
        </section>
      </section>
    );
  }

  function renderClassification() {
    return (
      <section className="page-content">
        <div className="page-title"><p className="eyebrow">Demo reference · not an uploaded-image prediction</p><h2>Intensity Classification</h2></div>
        <p className="demo-banner">No trained IMD intensity classifier is available. The existing ResNet-18 predicts four synthetic stages only.</p>
        <div className="hero-card classification-hero">
          <div><span className="muted-copy">Current demo classification</span><h2>{selectedCyclone.imd_classification}</h2><p>Confidence: {formatConfidence(selectedCyclone.classification_confidence)} · DEMO DATA</p></div>
          <div className="mini-panel"><span>Supporting wind speed</span><strong>{selectedCyclone.wind_speed_kmh} km/h</strong></div>
        </div>
        <ProbabilityDistribution probabilities={dashboard.imd_intensity_probabilities} source={dashboard.probabilities_source} />
        <section className="panel forecast-panel">
          <div className="panel-header"><h3>Future intensity forecast</h3><span className="source-badge">SEPARATE FROM CLASSIFICATION</span></div>
          <ResponsiveContainer width="100%" height={240}>
            <AreaChart data={dashboard.intensity_forecast}>
              <CartesianGrid stroke="rgba(255,255,255,0.08)" vertical={false} />
              <XAxis dataKey="name" stroke="#a7b4c7" />
              <YAxis stroke="#a7b4c7" unit=" km/h" />
              <Tooltip formatter={(value) => [`${value} km/h`, 'Forecast wind speed']} />
              <Area type="monotone" dataKey="value" stroke="#4ecdc4" fill="#4ecdc455" />
            </AreaChart>
          </ResponsiveContainer>
        </section>
      </section>
    );
  }

  function renderHistory() {
    return (
      <section className="page-content">
        <div className="page-title"><p className="eyebrow">Current browser session</p><h2>Prediction History</h2></div>
        <section className="panel">
          <h3>Uploaded image analyses</h3>
          {analysisHistory.length ? (
            <div className="historical-list">
              {analysisHistory.map((item, index) => (
                <article className="panel history-card" key={`${item.analysis_timestamp}-${index}`}>
                  <span className="source-badge">{item.data_mode || 'PROTOTYPE MODEL'}</span>
                  <h3>{item.filename}</h3>
                  <p>Cyclone detected: <strong>{item.cyclone_detected ? 'Yes' : 'No'}</strong></p>
                  <p>Prototype stage: <strong>{item.classification || 'Not classified'}</strong> · {formatConfidence(item.classification_confidence)}</p>
                  <time>{item.analysis_timestamp ? new Date(item.analysis_timestamp).toLocaleString('en-GB', { timeZone: 'UTC' }) : 'Timestamp unavailable'} UTC</time>
                </article>
              ))}
            </div>
          ) : (
            <p className="empty-state">No successful image analyses in this browser session.</p>
          )}
        </section>
        <div className="page-title"><p className="eyebrow">Past records · demo only</p><h2>Sample Historical Records</h2></div>
        <p className="demo-banner">These are synthetic historical examples, not authoritative records.</p>
        <div className="historical-list">
          {dashboard.historical_cyclones.map((cyclone) => (
            <article className="panel history-card" key={cyclone.name}>
              <span className="source-badge">HISTORICAL DEMO DATA</span>
              <h3>{cyclone.name}</h3>
              <p>Recorded classification: <strong>{cyclone.classification}</strong></p>
              <time>{new Date(cyclone.recorded_at).toLocaleString('en-GB', { timeZone: 'UTC' })} UTC</time>
            </article>
          ))}
        </div>
      </section>
    );
  }

  function renderPerformance() {
    return (
      <section className="page-content">
        <div className="page-title"><p className="eyebrow">Evaluation results</p><h2>Model Performance</h2></div>
        <ModelInformation information={dashboard.model_information} />
        {dashboard.model_metrics ? (
          <section className="panel">
            <h3>Trained model metrics</h3>
            <p>Metrics are reported by the backend evaluation record.</p>
            <pre className="metric-output">{JSON.stringify(dashboard.model_metrics, null, 2)}</pre>
          </section>
        ) : (
          <section className="panel">
            <h3>Evaluation metrics unavailable</h3>
            <p>The API does not provide evaluated accuracy, precision, recall, or a confusion matrix. No performance values are displayed or estimated.</p>
          </section>
        )}
      </section>
    );
  }

  function renderAlerts() {
    return (
      <section className="page-content">
        <div className="page-title"><p className="eyebrow">Classification-derived notifications</p><h2>Alerts</h2></div>
        <div className="alert-list">
          {dashboard.alerts.map((alert, index) => (
            <article className="panel alert-card" key={`${alert.title}-${index}`}>
              <span className="source-badge">{alert.data_type}</span>
              <h3>{alert.title}</h3>
              <p>{alert.details}</p>
            </article>
          ))}
        </div>
        <section className="panel">
          <h3>Risk assessment unavailable</h3>
          <p>No trained risk model or verified live hazard data is available. The demo notifications above are not operational alerts.</p>
        </section>
      </section>
    );
  }

  const pageContent = {
    dashboard: renderDashboard,
    analysis: renderAnalysis,
    track: renderTrack,
    classification: renderClassification,
    history: renderHistory,
    performance: renderPerformance,
    alerts: renderAlerts,
  }[activePage]();

  return (
    <div className="app-shell">
      <aside className="sidebar">
        <div className="brand-block">
          <div className="brand-mark">CS</div>
          <div><div className="brand-name">CYCLO SENSE</div><div className="brand-subtitle">SIH26070 · AI cyclone monitor</div></div>
        </div>
        <nav className="nav" aria-label="Main navigation">
          {navigation.map(([page, label], index) => (
            <button
              className={`nav-item ${activePage === page ? 'active' : ''}`}
              type="button"
              key={`${page}-${label}-${index}`}
              onClick={() => setActivePage(page)}
              aria-current={activePage === page ? 'page' : undefined}
            >
              {label}
            </button>
          ))}
        </nav>
        <div className="sidebar-model-note">
          <span>AVAILABLE CHECKPOINTS</span>
          <strong>ResNet-18 prototype</strong>
          <small>Binary detection + four synthetic stages</small>
        </div>
      </aside>

      <main className="main-panel">
        <header className="topbar">
          <div>
            <div className="eyebrow">Cyclone AI Monitor · prototype</div>
            <h1>CYCLO SENSE</h1>
          </div>
          <div className="topbar-status">
            {dashboardError && <button className="refresh-button" onClick={loadDashboard}>API refresh failed · retry</button>}
            <div className="status-badge">{dashboard.health.status === 'ok' ? 'System healthy' : 'System unavailable'}</div>
            {isDemo && <span className="demo-mode-badge">DEMO MODE</span>}
          </div>
        </header>
        {pageContent}
      </main>
    </div>
  );
}

function PredictionTable({ predictions }) {
  return (
    <section className="panel">
      <div className="panel-header"><h3>Current analysis summary</h3><span className="source-badge">DEMO DATA</span></div>
      <div className="prediction-table">
        <div className="table-head prediction-summary-head"><span>Prediction type</span><span>Result</span></div>
        {predictions.map((prediction) => (
          <div className="table-row prediction-summary-row" key={prediction.type}>
            <span>{prediction.type}</span><strong>{prediction.result}</strong>
          </div>
        ))}
      </div>
    </section>
  );
}

function ModelInformation({ information }) {
  return (
    <section className="panel model-information">
      <div className="panel-header"><h3>Model pipeline</h3><span className="source-badge">PROPOSED VS CURRENT PROTOTYPE</span></div>
      <div className="model-info-grid">
        <div><span>Proposed SIH architecture</span><strong>{information.proposed_architecture}</strong></div>
        <div><span>Input</span><strong>{information.input_size} satellite image</strong></div>
        <div><span>Proposed output</span><strong>8 IMD intensity classes</strong></div>
        <div><span>Current prototype</span><strong>{information.current_prototype_architecture} · {information.current_prototype_output}</strong></div>
      </div>
      {!information.proposed_model_implemented && (
        <p className="demo-note">The proposed MobileNetV2 eight-class model is not implemented. Existing ResNet-18 checkpoints were trained on synthetic images; the dashboard’s IMD probabilities remain illustrative demo data.</p>
      )}
    </section>
  );
}

export default App;
