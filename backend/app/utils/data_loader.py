from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from PIL import Image

REQUIRED_COLUMNS = {
    "image_path",
    "timestamp",
    "latitude",
    "longitude",
    "cyclone_id",
    "cyclone_name",
    "intensity",
    "wind_speed",
    "pressure",
    "classification",
    "is_cyclone",
}


def load_metadata(csv_path: str | Path) -> pd.DataFrame:
    """Load cyclone metadata from a CSV file and validate its schema."""
    path = Path(csv_path)
    if not path.exists():
        raise FileNotFoundError(f"Metadata file does not exist: {path}")

    dataframe = pd.read_csv(path)
    missing = REQUIRED_COLUMNS - set(dataframe.columns)
    if missing:
        raise ValueError(f"Metadata file is missing required columns: {sorted(missing)}")
    return dataframe


def load_image(image_path: str | Path) -> np.ndarray:
    """Read an image into a NumPy array."""
    path = Path(image_path)
    if not path.exists():
        raise FileNotFoundError(f"Image file does not exist: {path}")

    with Image.open(path) as image:
        array = np.asarray(image.convert("RGB"))
    return array


def resolve_image_path(metadata_row: dict[str, Any], project_root: str | Path | None = None) -> Path:
    """Resolve the image path from metadata generated by the demo loader."""
    image_path = Path(metadata_row["image_path"])
    if not image_path.is_absolute() and project_root is not None:
        image_path = Path(project_root) / image_path
    return image_path
